
import os
import numpy as np
import json 
from gurobipy import Model, GRB, quicksum


model = Model("OptimizationProblem")

with open("data.json", "r") as f:
    data = json.load(f)




### Define the parameters

ChopSawCuttingCapacity = data["ChopSawCuttingCapacity"] # shape: [], definition: Cutting capacity of a chop saw in pounds per day

ChopSawWaste = data["ChopSawWaste"] # shape: [], definition: Waste generated by a chop saw per day

SteelCutterCuttingCapacity = data["SteelCutterCuttingCapacity"] # shape: [], definition: Cutting capacity of a steel cutter in pounds per day

SteelCutterWaste = data["SteelCutterWaste"] # shape: [], definition: Waste generated by a steel cutter per day

TotalCuttingRequirement = data["TotalCuttingRequirement"] # shape: [], definition: Total metal cutting requirement per day in pounds

WasteLimit = data["WasteLimit"] # shape: [], definition: Maximum allowable waste per day in units



### Define the variables

ChopSaws = model.addVar(vtype=GRB.INTEGER, name="ChopSaws")

SteelCutters = model.addVar(vtype=GRB.INTEGER, name="SteelCutters")



### Define the constraints

model.addConstr(ChopSawCuttingCapacity * ChopSaws + SteelCutterCuttingCapacity * SteelCutters >= TotalCuttingRequirement)
model.addConstr(ChopSawWaste * ChopSaws + SteelCutterWaste * SteelCutters <= WasteLimit)
model.addConstr(ChopSaws >= 0)
model.addConstr(SteelCutters >= 0)


### Define the objective

model.setObjective(ChopSaws + SteelCutters, GRB.MINIMIZE)


### Optimize the model

model.optimize()



### Output optimal objective value

print("Optimal Objective Value: ", model.objVal)


if model.status == GRB.OPTIMAL:
    with open("output_solution.txt", "w") as f:
        f.write(str(model.objVal))
    print("Optimal Objective Value: ", model.objVal)
else:
    with open("output_solution.txt", "w") as f:
        f.write(model.status)
